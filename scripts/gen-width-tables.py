#!/usr/bin/env python
"""Generate src/layout/width_tables.rs from doclayout's and emojis' data.

rspandoc lays text out the way the doclayout library does, which measures
characters with doclayout's own width table (unicodeWidth.inc) and a map of
emoji that accept a variation selector or a skin tone (from the emojis
package's emojis.inc). Both are BSD-3-Clause data; this turns them into
Rust tables rather than retyping them.

Usage: gen-width-tables.py <doclayout>/src/Text/unicodeWidth.inc \
           <emojis>/src/Text/emojis.inc > src/layout/width_tables.rs
"""

import re
import sys

NAMED = {"NUL": 0, "DEL": 127}


def haskell_chars(lit: str) -> list[int]:
    """The code points of a Haskell char or string literal's contents."""
    out = []
    i = 0
    while i < len(lit):
        c = lit[i]
        if c != "\\":
            out.append(ord(c))
            i += 1
            continue
        rest = lit[i + 1 :]
        if rest.startswith("&"):
            i += 2
            continue
        m = re.match(r"\d+", rest)
        if m:
            out.append(int(m.group(0)))
            i += 1 + len(m.group(0))
            continue
        for name, code in NAMED.items():
            if rest.startswith(name):
                out.append(code)
                i += 1 + len(name)
                break
        else:
            out.append(ord(rest[0]))
            i += 2
    return out


def main() -> None:
    width_inc, emoji_inc = sys.argv[1], sys.argv[2]
    with open(width_inc, encoding="utf-8") as f:
        width_text = f.read()
    ranges = []
    for m in re.finditer(r"\(\s*'((?:\\[^']+|[^']))'\s*,\s*([A-Za-z]+)\s*\)", width_text):
        [code] = haskell_chars(m.group(1))
        ranges.append((code, m.group(2)))

    with open(emoji_inc, encoding="utf-8") as f:
        emoji_text = f.read()
    base = emoji_text[emoji_text.index("baseEmojis =") : emoji_text.index("zwjEmojis =")]
    emoji: dict[int, list[bool]] = {}
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', base):
        chars = haskell_chars(m.group(1))
        if not chars:
            continue
        first, second = chars[0], chars[1] if len(chars) > 1 else None
        info = emoji.setdefault(first, [False, False])
        if second is not None:
            info[0] |= 0xFE0E <= second <= 0xFE0F
            info[1] |= 0x1F3FB <= second <= 0x1F3FF

    print("// Generated by scripts/gen-width-tables.py from doclayout 0.5.0.3's")
    print("// unicodeWidth.inc and emojis 0.1.5's emojis.inc (both BSD-3-Clause,")
    print("// Copyright John MacFarlane). Do not edit by hand.")
    print()
    print("use super::width::Class;")
    print()
    print("/// Where each width class starts, in code point order.")
    print("pub const RANGES: &[(u32, Class)] = &[")
    for code, cls in ranges:
        print(f"    (0x{code:X}, Class::{cls}),")
    print("];")
    print()
    print("/// Emoji start characters: (code point, takes a variation selector,")
    print("/// takes a skin tone).")
    print("pub const EMOJI: &[(u32, bool, bool)] = &[")
    for code in sorted(emoji):
        v, s = emoji[code]
        print(f"    (0x{code:X}, {str(v).lower()}, {str(s).lower()}),")
    print("];")


if __name__ == "__main__":
    main()
