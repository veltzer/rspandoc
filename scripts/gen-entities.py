#!/usr/bin/env python
"""Generate src/entities.rs from tagsoup's HTML entity table.

The table is the HTML5 list of named character references, as tagsoup
0.14.8 (BSD-3-Clause, Copyright Neil Mitchell) carries it in
Text/HTML/TagSoup/Entity.hs: names with and without the trailing `;`, the
latter only for the legacy entities HTML allows unterminated.

Usage: gen-entities.py <tagsoup>/src/Text/HTML/TagSoup/Entity.hs > src/entities.rs
"""

import re
import sys


def main() -> None:
    with open(sys.argv[1], encoding="utf-8") as f:
        text = f.read()
    body = text[text.index("htmlEntities = ") :]
    pairs = []
    for m in re.finditer(r'"([^"]+)" \* "((?:\\x[0-9A-Fa-f]+)+)"', body):
        chars = "".join(chr(int(h, 16)) for h in re.findall(r"\\x([0-9A-Fa-f]+)", m.group(2)))
        pairs.append((m.group(1), chars))
    pairs.sort()
    print("// Generated by scripts/gen-entities.py from tagsoup 0.14.8's")
    print("// Text/HTML/TagSoup/Entity.hs (BSD-3-Clause, Copyright Neil Mitchell).")
    print("// Do not edit by hand.")
    print()
    print("/// HTML named character references, sorted by name.")
    print("pub const ENTITIES: &[(&str, &str)] = &[")
    for name, chars in pairs:
        escaped = "".join(f"\\u{{{ord(c):X}}}" for c in chars)
        print(f'    ("{name}", "{escaped}"),')
    print("];")


if __name__ == "__main__":
    main()
